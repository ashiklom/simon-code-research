"""Pilot report: extraction cost per product, storage, compression study, timing checks, skill."""

from __future__ import annotations

import re
from pathlib import Path

import pandas as pd

from . import config

PER_SITE = {"era5", "era5land", "merra2", "hrrr", "chirps3", "imerg_late", "gridmet", "daymet", "nldas2_forcing",
            "nldas2_noah", "nldas2_vic", "nldas2_mosaic"}
N_ALL = 305


def extraction_costs(log_dir: Path = config.DATA / "logs") -> pd.DataFrame:
    rows = []
    pat = re.compile(r"\[(\w+)\] done: (\d+) site\(s\), ([\d.]+) (\w+) decoded, (\d+) s")
    for f in sorted(log_dir.glob("*.log")):
        for m in pat.finditer(f.read_text(errors="ignore")):
            mult = {"B": 1e-6, "KB": 1e-3, "MB": 1, "GB": 1e3}[m.group(4)]
            rows.append({"product": m.group(1), "sites": int(m.group(2)), "decoded_MB": float(m.group(3)) * mult,
                         "seconds": int(m.group(5)), "log": f.name})
    df = pd.DataFrame(rows).drop_duplicates("product", keep="last")
    sizes = {}
    for d in (config.DATA / "store").glob("products-*.icechunk"):
        sizes[d.name.removeprefix("products-").removesuffix(".icechunk")] = sum(p.stat().st_size for p in d.rglob("*") if p.is_file()) / 1e6
    # final store size per product (after compaction) and the number of sites it holds
    from . import store

    n_sites = {}
    for name in sizes:
        try:
            from .products import registry

            at = store.group_attrs(store.readonly("products", name), store.group_path("products", name, registry.get(name).freq))
            n_sites[name] = len(at.get("site_end", {}))
        except Exception:
            pass
    df["s_per_site"] = df.seconds / df.sites
    df["est_hours_all_sites"] = df.apply(lambda r: r.s_per_site * N_ALL / 3600 if r["product"] in PER_SITE else float("nan"), axis=1)
    final = pd.DataFrame({"product": list(sizes), "final_store_MB": [sizes[k] for k in sizes],
                          "final_sites": [n_sites.get(k) for k in sizes]})
    final["MB_per_site"] = final.final_store_MB / final.final_sites
    return df.drop(columns=["store_MB"], errors="ignore").merge(final, on="product", how="outer")


def write_pilot_report():
    out = config.RESULTS / "pilot"
    out.mkdir(parents=True, exist_ok=True)
    cost = extraction_costs()
    cost.round(2).to_csv(out / "extract_costs.csv", index=False)
    parts = ["# Pilot report (12 USCRN stations)\n",
             "Generated by `uv run cpc report`. Inputs: extraction logs, `data/store`, `data/results/*_pilot.parquet`.\n",
             "## Extraction cost (pilot sites, full period)\n",
             "Per-site products scale with the number of sites; file-based products (PRISM, CHELSA, GEOS-FP, IMERG Final) "
             "read whole files and were run once for all 305 sites (their cost does not depend on site count).\n",
             "Columns: pilot extraction (`sites`, `seconds`, `s_per_site`, extrapolated `est_hours_all_sites` for per-site "
             "products) and the FINAL store after extracting all sites (`final_store_MB`, `final_sites`, `MB_per_site`).\n",
             cost[["product", "sites", "seconds", "s_per_site", "est_hours_all_sites", "final_store_MB", "final_sites",
                   "MB_per_site"]].round(2).to_markdown(index=False), "\n"]
    for name, title in (("compression_sizes.csv", "Compression study: encoded bytes per value"),
                        ("compression_metric_maxabsdiff.csv", "Compression study: max |metric difference| quantized vs lossless"),
                        ("day_window_overrides_pilot.csv", "Daily windows: documented vs best-aligned (median r over sites)")):
        f = out / name
        if f.exists():
            parts += [f"## {title}\n", pd.read_csv(f).round(4).to_markdown(index=False), "\n"]
    lag = out / "lagcheck_pilot.csv"
    if lag.exists():
        d = pd.read_csv(lag)
        h = d[d.scale == "hourly"].pivot_table(index=["product", "var"], columns="lag_h", values="r").round(3)
        parts += ["## Hourly timing check: median r vs lag (h; + = product shifted later)\n", h.to_markdown(), "\n"]
    mfile = config.DATA / "results" / "metrics_pilot.parquet"
    if mfile.exists():
        m = pd.read_parquet(mfile)
        sel = m[(m.method == "bilinear") & (m.scale == "daily") & (m.window == "common") & m.obs_var.isin(["tair", "tmax", "tmin", "pr", "sw", "rh"])
                & ~m["var"].str.endswith("_adj")]
        for metric in ("r", "bias", "rmse"):
            t = sel.pivot_table(index="product", columns="obs_var", values=metric, aggfunc="median").round(2)
            parts += [f"## Daily {metric}, common window, bilinear (median over pilot sites)\n", t.to_markdown(), "\n"]
        pr = sel[sel.obs_var == "pr"].groupby("product")[["ratio", "csi_1.0", "pod_1.0", "far_1.0"]].median().round(2)
        parts += ["## Daily precipitation detection (1 mm), common window\n", pr.to_markdown(), "\n"]
    (out / "pilot_report.md").write_text("\n".join(parts))
    return out / "pilot_report.md"
