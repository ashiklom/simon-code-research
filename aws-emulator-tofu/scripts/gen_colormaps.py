"""Vendor a handful of rio-tiler colormaps into lambdas/tiler_lite/colormaps.py (pure Python, no numpy)."""
from pathlib import Path

from rio_tiler.colormap import cmap

NAMES = ["viridis", "magma", "inferno", "cividis", "terrain", "gray", "greys", "blues", "rdylgn", "spectral"]
out = Path(__file__).resolve().parent.parent / "lambdas" / "tiler_lite" / "colormaps.py"
lines = ['"""256-entry RGB colormaps copied from rio-tiler (generated by scripts/gen_colormaps.py)."""', "",
         "COLORMAPS = {"]
for n in NAMES:
    cm = cmap.get(n)
    hexstr = "".join(f"{int(cm[i][0]):02x}{int(cm[i][1]):02x}{int(cm[i][2]):02x}" for i in range(256))
    lines.append(f'    "{n}": bytes.fromhex(')
    for k in range(0, len(hexstr), 96):
        lines.append(f'        "{hexstr[k:k+96]}"')
    lines.append("    ),")
lines.append("}")
out.write_text("\n".join(lines) + "\n")
print(out, out.stat().st_size)
